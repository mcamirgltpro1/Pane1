import React, { useState } from 'react';
import { 
  FileBarChart, 
  Copy, 
  Share2, 
  Printer, 
  Check, 
  Sparkles, 
  Calendar, 
  Flame, 
  AlertCircle,
  TrendingUp,
  BarChart2
} from 'lucide-react';
import { AppState, WeeklyReportData } from '../types';
import { translations, toPersianDigits } from '../utils/translations';
import { playChime, triggerVibration } from '../utils/audio';

interface ReportsViewProps {
  state: AppState;
  onSaveReport: (report: WeeklyReportData) => void;
}

export const ReportsView: React.FC<ReportsViewProps> = ({
  state,
  onSaveReport,
}) => {
  const t = translations[state.language];

  const [copied, setCopied] = useState(false);
  const [mostProductiveDay, setMostProductiveDay] = useState(state.language === 'fa' ? 'سه‌شنبه' : 'Tuesday');
  const [mainObstacle, setMainObstacle] = useState(
    state.language === 'fa' 
      ? 'محدودیت زمان در روز پنج‌شنبه به علت کارگاه عملی' 
      : 'Limited free time on Thursday due to practical workshop'
  );
  const [personalNotes, setPersonalNotes] = useState(
    state.language === 'fa'
      ? 'روند مطالعه پایتون و الکترونیک منظم پیش رفت. نیاز به تمرکز بیشتر روی مباحث خازن و تست ترانزیستور.'
      : 'AI Python and electronics study went according to plan. Need more focus on capacitor theory and BJT testing.'
  );

  // Compute live current weekly metrics from state
  const aiCourse = state.courses.find((c) => c.id === 'course-ai-python') || state.courses[0];
  const mathCourse = state.courses.find((c) => c.id === 'course-math-techno-sharif') || state.courses[1];

  const completedTasksCount = state.tasks.filter((t) => t.status === 'completed').length;
  const postponedTasksCount = state.tasks.filter((t) => t.status === 'postponed').length;

  const totalActivities = state.scheduleActivities.length;
  const completedActivities = state.scheduleActivities.filter((a) => a.status === 'completed').length;
  const schedulePercentage = totalActivities > 0 ? Math.round((completedActivities / totalActivities) * 100) : 85;

  const totalElecMinutes = state.electronicsResources.reduce((acc, r) => acc + r.studyMinutesLogged, 0);

  // Generate Persian / English formatted text report
  const generateFormattedText = () => {
    if (state.language === 'fa') {
      return `📊 گزارش عملکرد و پیشرفت هفتگی (برنامه شخصی من)
----------------------------------------
🔹 دوره پایتون و هوش مصنوعی:
   ${toPersianDigits(aiCourse ? Math.min(aiCourse.completedLessons, aiCourse.weeklyTarget) : 3, 'fa')} از ${toPersianDigits(aiCourse ? aiCourse.weeklyTarget : 4, 'fa')} جلسه هدف هفتگی انجام شد.
   (باقی‌مانده کل دوره: ${toPersianDigits(aiCourse ? aiCourse.totalLessons - aiCourse.completedLessons : 26, 'fa')} درس)

🔹 دوره ریاضی تکنو شریف:
   ${toPersianDigits(mathCourse ? Math.min(mathCourse.completedLessons, mathCourse.weeklyTarget) : 1, 'fa')} از ${toPersianDigits(mathCourse ? mathCourse.weeklyTarget : 1, 'fa')} جلسه هدف هفتگی انجام شد.

🔹 خودآموزی الکترونیک:
   ۲ از ۲ جلسه هفتگی انجام شد (مجموع مطالعه: ${toPersianDigits(totalElecMinutes, 'fa')} دقیقه).
   آزمایش‌های عملی ثبت شده: ${toPersianDigits(state.experiments.length, 'fa')} مدار.

🔹 وظایف و برنامه‌ها:
   - وظایف انجام شده: ${toPersianDigits(completedTasksCount, 'fa')} مورد
   - وظایف تغییر زمان یافته: ${toPersianDigits(postponedTasksCount, 'fa')} مورد
   - درصد تحقق برنامه هفتگی: ${toPersianDigits(schedulePercentage, 'fa')}٪

🌟 پرکارترین روز هفته: ${mostProductiveDay}
⚠️ مانع و چالش اصلی: ${mainObstacle}
📝 یادداشت‌های ارزیابی:
${personalNotes}
----------------------------------------
تولید شده توسط برنامه شخصی من (My Planner)`;
    }

    return `📊 Weekly Personal Progress Report (My Planner)
----------------------------------------
🔹 AI & Python Course:
   ${aiCourse ? Math.min(aiCourse.completedLessons, aiCourse.weeklyTarget) : 3} / ${aiCourse ? aiCourse.weeklyTarget : 4} target recorded sessions completed.
   (Total remaining backlog: ${aiCourse ? aiCourse.totalLessons - aiCourse.completedLessons : 26} lessons)

🔹 Techno Sharif Mathematics:
   ${mathCourse ? Math.min(mathCourse.completedLessons, mathCourse.weeklyTarget) : 1} / ${mathCourse ? mathCourse.weeklyTarget : 1} target session completed.

🔹 Electronics Self-Study:
   2 / 2 weekly study sessions completed (Total study time: ${totalElecMinutes} minutes).
   Practical experiments: ${state.experiments.length} circuits logged.

🔹 Tasks & Schedule:
   - Tasks completed: ${completedTasksCount}
   - Tasks postponed: ${postponedTasksCount}
   - Weekly schedule completion rate: ${schedulePercentage}%

🌟 Most Productive Day: ${mostProductiveDay}
⚠️ Main Obstacle: ${mainObstacle}
📝 Personal Reflections & Notes:
${personalNotes}
----------------------------------------
Generated by My Planner (Offline Personal Cockpit)`;
  };

  const handleCopy = () => {
    const text = generateFormattedText();
    navigator.clipboard.writeText(text);
    setCopied(true);
    playChime('gentle');
    setTimeout(() => setCopied(false), 2500);
  };

  const handleShare = () => {
    const text = generateFormattedText();
    if (navigator.share) {
      navigator.share({
        title: t.weeklyReportTitle,
        text,
      }).catch(() => {});
    } else {
      handleCopy();
    }
  };

  const handlePrint = () => {
    window.print();
  };

  const handleSaveToArchive = () => {
    const report: WeeklyReportData = {
      id: `rep-${Date.now()}`,
      weekRange: state.language === 'fa' ? 'هفته جاری' : 'Current Week',
      createdAt: new Date().toISOString(),
      aiCompleted: aiCourse ? aiCourse.completedLessons : 3,
      aiTarget: aiCourse ? aiCourse.weeklyTarget : 4,
      mathCompleted: mathCourse ? mathCourse.completedLessons : 1,
      mathTarget: mathCourse ? mathCourse.weeklyTarget : 1,
      electronicsSessions: 2,
      electronicsTarget: 2,
      electronicsMinutes: totalElecMinutes,
      tasksCompleted: completedTasksCount,
      tasksPostponed: postponedTasksCount,
      scheduleCompletionRate: schedulePercentage,
      mostProductiveDay,
      mainObstacle,
      notes: personalNotes,
      schoolStatus: 'All assignments submitted on time',
    };
    onSaveReport(report);
    playChime('complete');
    triggerVibration([50]);
  };

  return (
    <div className="space-y-5 pb-24 px-4 pt-4 max-w-2xl mx-auto">
      {/* 1. Header with Print & Copy Actions */}
      <div className="flex items-center justify-between gap-3 no-print">
        <div>
          <h2 className="text-lg font-bold text-white flex items-center gap-2">
            <FileBarChart className="w-5 h-5 text-amber-400" />
            <span>{t.weeklyReportTitle}</span>
          </h2>
          <p className="text-xs text-zinc-400">
            {state.language === 'fa' ? 'تولید خودکار بر اساس داده‌های فعالیت و یادگیری' : 'Generated automatically from your study & task logs'}
          </p>
        </div>

        <div className="flex items-center gap-1.5 shrink-0">
          <button
            onClick={handleCopy}
            className="min-h-[40px] px-3 rounded-xl bg-zinc-900 border border-zinc-800 text-zinc-200 hover:text-amber-400 hover:border-amber-400/40 text-xs font-semibold flex items-center gap-1.5 active:scale-95 transition-all"
          >
            {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
            <span>{copied ? (state.language === 'fa' ? 'کپی شد' : 'Copied!') : t.copyReport}</span>
          </button>

          <button
            onClick={handlePrint}
            title={t.exportPdf}
            className="min-h-[40px] min-w-[40px] rounded-xl bg-amber-400 text-black hover:bg-amber-300 flex items-center justify-center font-bold shadow-sm active:scale-95 transition-all"
          >
            <Printer className="w-4 h-4" />
          </button>
        </div>
      </div>

      {/* 2. Visual Analytics Strip */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5 no-print">
        <div className="bg-[#151515] border border-zinc-800 p-3.5 rounded-2xl text-center">
          <span className="text-[11px] text-zinc-400 block mb-1">{state.language === 'fa' ? 'پیشرفت برنامه' : 'Schedule'}</span>
          <span className="text-xl font-bold text-amber-400 font-mono tabular-nums">{toPersianDigits(schedulePercentage, state.language)}%</span>
        </div>
        <div className="bg-[#151515] border border-zinc-800 p-3.5 rounded-2xl text-center">
          <span className="text-[11px] text-zinc-400 block mb-1">{state.language === 'fa' ? 'وظایف تکمیل' : 'Tasks Done'}</span>
          <span className="text-xl font-bold text-emerald-400 font-mono tabular-nums">{toPersianDigits(completedTasksCount, state.language)}</span>
        </div>
        <div className="bg-[#151515] border border-zinc-800 p-3.5 rounded-2xl text-center">
          <span className="text-[11px] text-zinc-400 block mb-1">{state.language === 'fa' ? 'ساعات مطالعه' : 'Study Time'}</span>
          <span className="text-xl font-bold text-zinc-200 font-mono tabular-nums">{toPersianDigits(Math.round(totalElecMinutes / 60), state.language)}h</span>
        </div>
        <div className="bg-[#151515] border border-zinc-800 p-3.5 rounded-2xl text-center">
          <span className="text-[11px] text-zinc-400 block mb-1">{state.language === 'fa' ? 'آزمایش‌ها' : 'Experiments'}</span>
          <span className="text-xl font-bold text-amber-300 font-mono tabular-nums">{toPersianDigits(state.experiments.length, state.language)}</span>
        </div>
      </div>

      {/* 3. The Formatted Report Card (Clean & Printable) */}
      <div className="bg-[#151515] border border-zinc-800 rounded-3xl p-5 shadow-xl space-y-4 font-sans print:bg-white print:text-black print:border-none print:shadow-none">
        <div className="flex items-center justify-between border-b border-zinc-800 pb-3">
          <div>
            <h3 className="text-base font-bold text-white print:text-black">
              {t.weeklyReportTitle}
            </h3>
            <span className="text-xs text-zinc-400 print:text-zinc-600">
              {new Date().toLocaleDateString(state.language === 'fa' ? 'fa-IR' : 'en-US')}
            </span>
          </div>
          <span className="text-xs px-2.5 py-1 rounded-full bg-amber-400/10 text-amber-400 border border-amber-400/30 font-semibold print:border-zinc-300 print:text-black">
            {state.language === 'fa' ? 'آماده ارسال' : 'Ready'}
          </span>
        </div>

        {/* Courses Performance Strip */}
        <div className="space-y-2 text-xs">
          <div className="flex items-center justify-between p-2.5 rounded-xl bg-zinc-900/60 print:bg-zinc-100">
            <span className="font-semibold text-zinc-200 print:text-black">{t.aiCourse}</span>
            <span className="font-mono text-amber-400 print:text-black font-bold">
              {toPersianDigits(aiCourse ? Math.min(aiCourse.completedLessons, aiCourse.weeklyTarget) : 3, state.language)} / {toPersianDigits(aiCourse ? aiCourse.weeklyTarget : 4, state.language)} {state.language === 'fa' ? 'جلسه' : 'sessions'}
            </span>
          </div>

          <div className="flex items-center justify-between p-2.5 rounded-xl bg-zinc-900/60 print:bg-zinc-100">
            <span className="font-semibold text-zinc-200 print:text-black">{t.mathCourse}</span>
            <span className="font-mono text-amber-400 print:text-black font-bold">
              {toPersianDigits(mathCourse ? Math.min(mathCourse.completedLessons, mathCourse.weeklyTarget) : 1, state.language)} / {toPersianDigits(mathCourse ? mathCourse.weeklyTarget : 1, state.language)} {state.language === 'fa' ? 'جلسه' : 'session'}
            </span>
          </div>

          <div className="flex items-center justify-between p-2.5 rounded-xl bg-zinc-900/60 print:bg-zinc-100">
            <span className="font-semibold text-zinc-200 print:text-black">{t.electronicsTitle}</span>
            <span className="font-mono text-amber-400 print:text-black font-bold">
              {toPersianDigits(2, state.language)} / {toPersianDigits(2, state.language)} {state.language === 'fa' ? 'جلسه' : 'sessions'} ({toPersianDigits(totalElecMinutes, state.language)} {t.studyMinutes})
            </span>
          </div>
        </div>

        {/* Inputs for Productivity & Obstacles */}
        <div className="space-y-3 pt-2">
          <div>
            <label className="block text-xs font-semibold text-zinc-400 mb-1">
              {t.mostProductiveDay}
            </label>
            <input
              type="text"
              value={mostProductiveDay}
              onChange={(e) => setMostProductiveDay(e.target.value)}
              className="w-full bg-zinc-900 border border-zinc-800 rounded-xl px-3 py-2 text-xs text-white focus:outline-none focus:border-amber-400 print:bg-transparent print:text-black print:border-zinc-300"
            />
          </div>

          <div>
            <label className="block text-xs font-semibold text-zinc-400 mb-1">
              {t.mainObstacle}
            </label>
            <input
              type="text"
              value={mainObstacle}
              onChange={(e) => setMainObstacle(e.target.value)}
              className="w-full bg-zinc-900 border border-zinc-800 rounded-xl px-3 py-2 text-xs text-white focus:outline-none focus:border-amber-400 print:bg-transparent print:text-black print:border-zinc-300"
            />
          </div>

          <div>
            <label className="block text-xs font-semibold text-zinc-400 mb-1">
              {t.personalNotes}
            </label>
            <textarea
              value={personalNotes}
              onChange={(e) => setPersonalNotes(e.target.value)}
              rows={3}
              className="w-full bg-zinc-900 border border-zinc-800 rounded-xl px-3 py-2 text-xs text-white focus:outline-none focus:border-amber-400 print:bg-transparent print:text-black print:border-zinc-300"
            />
          </div>
        </div>

        {/* Report Footer Actions */}
        <div className="pt-3 border-t border-zinc-800 flex items-center justify-between no-print">
          <button
            onClick={handleSaveToArchive}
            className="px-4 py-2 rounded-xl bg-zinc-900 border border-zinc-800 hover:border-zinc-700 text-xs text-zinc-300 font-semibold"
          >
            {state.language === 'fa' ? 'ذخیره در آرشیو گزارش‌ها' : 'Save to Archive'}
          </button>

          <button
            onClick={handleShare}
            className="px-4 py-2 rounded-xl bg-amber-400 text-black text-xs font-bold hover:bg-amber-300 flex items-center gap-1.5 shadow-sm"
          >
            <Share2 className="w-3.5 h-3.5" />
            <span>{t.shareReport}</span>
          </button>
        </div>
      </div>

      {/* 4. Past Reports Archive */}
      {state.weeklyReports.length > 0 && (
        <div className="space-y-3 no-print">
          <h3 className="text-xs font-bold text-zinc-400 uppercase tracking-wider px-1">
            {t.reportHistory}
          </h3>

          {state.weeklyReports.map((rep) => (
            <div
              key={rep.id}
              className="p-4 rounded-2xl bg-[#151515] border border-zinc-800 space-y-2"
            >
              <div className="flex items-center justify-between">
                <span className="text-sm font-bold text-white">{rep.weekRange}</span>
                <span className="text-xs text-amber-400 font-mono">{toPersianDigits(rep.scheduleCompletionRate, state.language)}% {state.language === 'fa' ? 'تحقق' : 'rate'}</span>
              </div>
              <p className="text-xs text-zinc-400">{rep.notes}</p>
            </div>
          ))}
        </div>
      )}
    </div>
  );
};
