export function toPersianDigits(n: number | string, lang: Language): string {
  if (lang !== 'fa') return String(n);
  const persianDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  return String(n).replace(/[0-9]/g, (w) => persianDigits[+w]);
}
